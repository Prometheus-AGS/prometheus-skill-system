#!/usr/bin/env node
// Generates Claude Code native slash command files from skills SKILL.md frontmatter.
// Each output file: description frontmatter + file-reference body + $ARGUMENTS.
// Usage: node scripts/generate-commands.js [--output ~/.claude/commands] [--uninstall]

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { homedir } from 'os';
import yaml from 'js-yaml';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const SKILLS_DIR = path.join(ROOT, 'skills');
const SKIP_DIRS = new Set(['imported', 'node_modules', 'target', 'dist', '.git']);

const args = process.argv.slice(2);
const outputIdx = args.indexOf('--output');
const outputDir =
  outputIdx !== -1
    ? path.resolve(args[outputIdx + 1].replace(/^~/, homedir()))
    : path.join(homedir(), '.claude', 'commands');
const UNINSTALL = args.includes('--uninstall');

function findSkillMds(dir, results = []) {
  let entries;
  try {
    entries = fs.readdirSync(dir, { withFileTypes: true });
  } catch {
    return results;
  }
  for (const entry of entries) {
    if (SKIP_DIRS.has(entry.name) || entry.name.startsWith('.')) continue;
    const fullPath = path.join(dir, entry.name);
    if (entry.isDirectory()) findSkillMds(fullPath, results);
    else if (entry.name === 'SKILL.md') results.push(fullPath);
  }
  return results;
}

function parseFrontmatter(content) {
  const match = content.match(/^---\n([\s\S]*?)\n---/);
  if (!match) return null;
  try {
    return yaml.load(match[1]);
  } catch {
    return null;
  }
}

const skillMds = findSkillMds(SKILLS_DIR);
let count = 0;
let skipped = 0;

if (UNINSTALL) {
  for (const skillMdPath of skillMds) {
    const content = fs.readFileSync(skillMdPath, 'utf-8');
    const fm = parseFrontmatter(content);
    if (!fm?.name) {
      skipped++;
      continue;
    }
    const target = path.join(outputDir, `${fm.name}.md`);
    try {
      fs.unlinkSync(target);
      count++;
    } catch {
      /* already gone */
    }
  }
  console.log(`✅ Removed ${count} command file(s) from ${outputDir} (skipped ${skipped})`);
} else {
  fs.mkdirSync(outputDir, { recursive: true });
  for (const skillMdPath of skillMds) {
    const content = fs.readFileSync(skillMdPath, 'utf-8');
    const fm = parseFrontmatter(content);
    if (!fm?.name || !fm?.description) {
      skipped++;
      continue;
    }

    // Point at the SKILL.md by ABSOLUTE path, and instruct the agent to read it.
    //
    // The previous form emitted `{{file:<repo-relative path>}}`. Claude Code does
    // not expand that token, so the literal text `{{file:skills/.../SKILL.md}}`
    // reached the model as the entire prompt body and every one of these slash
    // commands silently did nothing — the skill was never loaded. A relative path
    // could not have worked regardless: the command file lives in
    // ~/.claude/commands/, where a path like `skills/learn/sync-status/SKILL.md`
    // resolves against the wrong root.
    //
    // `{{file:}}` IS valid for OpenCode, which expands it natively — see the
    // opencode branch of scripts/register-slash-commands.sh, which passes an
    // absolute path. This generator targets Claude Code, which needs the
    // read-then-follow form already used for Codex prompts.
    const absPath = skillMdPath.replace(/\\/g, '/');
    // Collapse whitespace BEFORE truncating. 153 of the pack's SKILL.md files
    // wrap `description:` across multiple lines; emitting a raw newline inside
    // a double-quoted YAML scalar produces invalid frontmatter, and the loader
    // then falls through to the next line for the description. Slicing first
    // would also let a trailing backslash escape the closing quote.
    const desc = fm.description
      .replace(/\s+/g, ' ')
      .trim()
      .slice(0, 200)
      .replace(/\\/g, '\\\\')
      .replace(/"/g, '\\"');
    const cmdContent =
      `---\ndescription: "${desc}"\n---\n\n` +
      `<!-- generated by prometheus-skill-pack: scripts/generate-commands.js -->\n\n` +
      `Read \`${absPath}\` in full, then follow its instructions to execute this skill.\n\n` +
      `$ARGUMENTS\n`;

    fs.writeFileSync(path.join(outputDir, `${fm.name}.md`), cmdContent, 'utf-8');
    count++;
  }
  console.log(`✅ Generated ${count} command file(s) → ${outputDir} (skipped ${skipped})`);
}
